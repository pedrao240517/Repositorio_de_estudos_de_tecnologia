package exercicioNoCodigoJava.iniciante.loops;

public class Dowhile {
    static void main(String[] args) {

        int cont = 1;

        do {
            System.out.println("Imprimi o bloco "+ cont);
            cont = cont + 1;
        }while (cont <= 10); // loop infinito se condição for falso e não mudar o valor da mémoria  pra true







    }
}
